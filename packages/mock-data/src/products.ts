export function getProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id)
}

export function getProductBySlug(slugOrId: string): Product | undefined {
  const norm = slugOrId.toLowerCase().trim()
  return products.find((p) => {
    const pSlug = p.slug?.toLowerCase().trim()
    const pId = p.id?.toLowerCase().trim()
    return (
      pSlug === norm ||
      pId === norm ||
      pSlug?.replace(/[^a-z0-9]/g, "-") === norm
    )
  })
}

export function getProductsByCategory(slugOrId: string): Product[] {
  const norm = slugOrId.toLowerCase().trim()
  const cat = categories.find(
    (c) => c.slug.toLowerCase().trim() === norm || c.id.toLowerCase().trim() === norm
  )

  if (cat) {
    if (cat.level === 1) {
      const childIds = new Set(
        categories
          .filter((c) => c.parentId === cat.id)
          .map((c) => c.id.toLowerCase())
      )
      return products.filter((p) => {
        const pCat = p.categoryId?.toLowerCase()
        const pSub = p.subcategoryId?.toLowerCase()
        return (
          pCat === cat.id.toLowerCase() ||
          pCat === cat.slug.toLowerCase() ||
          (pSub && childIds.has(pSub))
        )
      })
    } else {
      return products.filter((p) => {
        const pSub = p.subcategoryId?.toLowerCase()
        return pSub === cat.id.toLowerCase() || pSub === cat.slug.toLowerCase()
      })
    }
  }

  return products.filter((p) => {
    return (
      p.categoryId?.toLowerCase() === norm ||
      p.subcategoryId?.toLowerCase() === norm ||
      p.tags?.some((t) => t.toLowerCase() === norm)
    )
  })
}

export function getProductsBySubcategory(slugOrId: string): Product[] {
  const norm = slugOrId.toLowerCase().trim()
  const matchedCategory = categories.find(
    (c) => c.slug.toLowerCase().trim() === norm || c.id.toLowerCase().trim() === norm
  )
  const targetId = matchedCategory ? matchedCategory.id.toLowerCase() : norm
  const targetSlug = matchedCategory ? matchedCategory.slug.toLowerCase() : norm

  return products.filter((p) => {
    const pSubId = p.subcategoryId?.toLowerCase()
    const pCatId = p.categoryId?.toLowerCase()
    return (
      pSubId === targetId ||
      pSubId === targetSlug ||
      pCatId === targetId ||
      pCatId === targetSlug ||
      p.tags?.some((t) => t.toLowerCase() === targetSlug || t.toLowerCase() === targetId)
    )
  })
}

export function getProductsByBrand(brandSlugOrId: string): Product[] {
  const norm = brandSlugOrId.toLowerCase().replace(/[^a-z0-9]/g, "-")
  return products.filter((p) => {
    const pBrandSlug = p.brandName.toLowerCase().replace(/[^a-z0-9]/g, "-")
    const pBrandId = p.brandId?.toLowerCase()
    return (
      norm === pBrandSlug ||
      norm === pBrandId ||
      norm === p.brandName.toLowerCase() ||
      p.brandName.toLowerCase().includes(norm.replace(/-/g, " "))
    )
  })
}

export function getProductsByCountry(country: string): Product[] {
  const norm = country.toLowerCase()
  return products.filter(
    (p) => p.originCountry.toLowerCase() === norm
  )
}

export function getRelatedProducts(
  productId: string,
  type?: "bundle" | "brand" | "category"
): Product[] {
  const product = getProductById(productId) || getProductBySlug(productId)
  if (!product) return []

  if (type === "bundle") {
    const explicitRelated = (product.relatedProductIds || [])
      .map((id) => getProductById(id) || getProductBySlug(id))
      .filter((p): p is Product => p !== undefined && p.id !== product.id)

    if (explicitRelated.length >= 2) {
      return explicitRelated.slice(0, 2)
    }

    const complementary = products.filter(
      (p) =>
        p.id !== product.id &&
        !explicitRelated.some((er) => er.id === p.id) &&
        (p.categoryId === product.categoryId ||
          p.badges?.includes("bestseller") ||
          p.badges?.includes("offer"))
    )

    return [...explicitRelated, ...complementary].slice(0, 2)
  }

  if (type === "brand") {
    return products
      .filter(
        (p) =>
          p.id !== product.id &&
          (p.brandId === product.brandId || p.brandName === product.brandName)
      )
      .slice(0, 6)
  }

  if (type === "category") {
    return products
      .filter(
        (p) =>
          p.id !== product.id &&
          (p.subcategoryId === product.subcategoryId ||
            p.categoryId === product.categoryId)
      )
      .slice(0, 6)
  }

  if (product.relatedProductIds && product.relatedProductIds.length > 0) {
    const list = products.filter((p) => product.relatedProductIds?.includes(p.id))
    if (list.length > 0) return list
  }

  return products
    .filter((p) => p.id !== product.id && p.categoryId === product.categoryId)
    .slice(0, 4)
}