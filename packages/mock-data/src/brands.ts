export function getAllBrands(): Brand[] {
  return brands.filter((b) => b.isActive !== false)
}

export function getFeaturedBrands(limit = 12): Brand[] {
  return getAllBrands()
    .filter((b) => b.featured)
    .sort((a, b) => (b.productCount ?? 0) - (a.productCount ?? 0))
    .slice(0, limit)
}

export function getBrandBySlug(slug: string): Brand | undefined {
  const norm = slug.toLowerCase().trim()
  return brands.find((b) => {
    const bSlug = b.slug.toLowerCase().trim()
    const bId = b.id.toLowerCase().trim()
    const bName = b.name.toLowerCase().trim().replace(/[^a-z0-9]/g, "-")
    return bSlug === norm || bId === norm || bName === norm
  })
}

export function searchBrands(query: string): Brand[] {
  const q = query.toLowerCase().trim()
  if (!q) return getAllBrands()

  return getAllBrands().filter((b) => {
    const nameMatch = b.name.toLowerCase().includes(q)
    const enMatch = b.nameEn?.toLowerCase().includes(q) ?? false
    const zhMatch = b.nameZh?.includes(q) ?? false
    const countryMatch = b.countryOfOrigin.toLowerCase().includes(q)
    const descMatch = (b.descriptionEn?.toLowerCase().includes(q) ?? false) || (b.descriptionZh?.includes(q) ?? false)
    return nameMatch || enMatch || zhMatch || countryMatch || descMatch
  })
}

export function getBrandsByInitial(initial: string): Brand[] {
  const norm = initial.toUpperCase().trim()
  const activeBrands = getAllBrands()

  if (norm === "0-9" || norm === "NUM") {
    return activeBrands.filter((b) => /^[0-9]/.test(b.name.trim()))
  }

  return activeBrands.filter((b) => b.name.trim().toUpperCase().startsWith(norm))
}

export function getAvailableBrandInitials(): Set<string> {
  const initials = new Set<string>()
  for (const brand of getAllBrands()) {
    const firstChar = brand.name.trim().charAt(0).toUpperCase()
    if (/[0-9]/.test(firstChar)) {
      initials.add("0-9")
    } else if (/[A-Z]/.test(firstChar)) {
      initials.add(firstChar)
    }
  }
  return initials
}

export function getBrandLogo(brandName: string): string | undefined {
  const normalized = brandName.toLowerCase().trim()
  const found = brands.find((b) => {
    const bName = b.name.toLowerCase().trim()
    const bSlug = b.slug.toLowerCase().trim()
    return (
      bName === normalized ||
      bSlug === normalized ||
      bName.includes(normalized) ||
      normalized.includes(bName)
    )
  })
  return found?.logoUrl
}